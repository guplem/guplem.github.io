def generate(case: dict) -> dict:
    """One map for one test case, through the Bun runner."""
    if not os.environ.get("OPENROUTER_API_KEY"):
        sys.exit("Set OPENROUTER_API_KEY to generate maps.")
    completed = subprocess.run(
        [BUN, str(HERE / "runTestCase.js"), json.dumps(case)],
        capture_output=True,
        text=True,
        encoding="utf8",
        cwd=PROJECT,
    )
    if completed.returncode != 0:
        raise RuntimeError(f"{case['id']}: {completed.stderr.strip().splitlines()[-1] if completed.stderr else 'failed'}")
    return json.loads(completed.stdout)


def upload_image(path: Path) -> dict:
    """Put a PNG in Galtea's storage and return the content part that names it in an output envelope."""
    import requests

    presign = cli("storage", "generate-put-url", "--key", f"ai-world-gen/{path.parent.name}/{path.name}", "--file-type", "file")
    data = path.read_bytes()
    response = requests.put(presign["uploadPresignedUrl"], data=data, headers={"Content-Type": "image/png"}, timeout=60)
    response.raise_for_status()
    object_url = presign["downloadPresignedUrl"].split("?")[0]
    host, object_path = object_url.split("/")[2], "/".join(object_url.split("/")[3:])
    return {
        "type": "file",
        "uri": f"s3://{host.split('.s3.')[0]}/{object_path}",
        "mimeType": "image/png",
        "filename": path.name,
        "sizeBytes": len(data),
    }


STOPPING_REASON = "The map is complete: every cell was decided in this one turn."


def finish_session(session_id: str) -> None:
    """Mark a session COMPLETED. A session stays PENDING until something says the conversation ended;
    a map is one turn, so it ends as soon as the result is logged. The SDK has no call for this, the CLI has."""
    cli("sessions", "finish", session_id, stdin={"stoppingReason": STOPPING_REASON})


def render_results(version_name: str, results: dict[str, dict]) -> dict[str, Path]:
    """Draw every map of a run to results/<version>/<case>.png. Returns case id -> path."""
    import renderMap

    manifest = renderMap.load_manifest(BUN)
    preset_tags = renderMap.load_preset_tags(BUN)
    sheet = renderMap.load_sheet()
    folder = RESULTS_DIR / version_name
    folder.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for case_id, result in results.items():
        vocabulary = result["vocabulary"]
        tags = renderMap.tags_by_type(vocabulary) if isinstance(vocabulary.get("elements"), list) else preset_tags[result["input"]["preset"]]
        path = folder / f"{case_id}.png"
        renderMap.render_map(result["grid"], tags, sheet, manifest).save(path)
        paths[case_id] = path
    return paths


def git_description() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=PROJECT).stdout.strip()
        return f"commit {sha}"
    except OSError:
        return "unknown commit"


def judge_metric_names(config: dict) -> list[str]:
    """The judge metrics to ask Galtea for, when `setup` created any. Galtea takes them by name, not id."""
    return list((config.get("judgeMetricIds") or {}).keys())


def run(version_name: str, description: str | None, parallel: int, only: list[str] | None, images: bool = True) -> None:
    galtea = galtea_client()
    config = read_config()
    if not config.get("testCaseIds"):
        sys.exit("Run `python evaluate.py setup` first.")
    rules = read_rules()
    cases = [case for dataset in read_cases()["datasets"] for case in dataset["cases"]]
    if only:
        cases = [case for case in cases if case["id"] in only]

    decision_model = os.environ.get("AI_WORLD_GEN_DECISION_MODEL") or "~typesafe/jev-latest"
    narrative_model = os.environ.get("AI_WORLD_GEN_NARRATIVE_MODEL") or "anthropic/claude-sonnet-5"
    models_line = f"decision model {decision_model}; narrative model {narrative_model}"
    try:
        version = galtea.versions.get_by_name(config["productId"], version_name)
    except Exception:  # the SDK raises EntityNotFoundException for a name that does not exist yet
        version = None
    if version is None:
        version = galtea.versions.create(
            product_id=config["productId"],
            name=version_name,
            description=f"{description or 'AI World Gen'} ({git_description()}; {models_line})",
            model_id=None,
        )
        if version is None:
            sys.exit("Could not create the version.")
        print(f"version: created {version_name} ({version.id})")
    else:
        print(f"version: found {version_name} ({version.id})")

    RESULTS_DIR.mkdir(exist_ok=True)
    results: dict[str, dict] = {}
    started = time.time()

    def one(case: dict) -> tuple[str, dict]:
        print(f"  generating {case['id']} ...", flush=True)
        return case["id"], generate(case)

    with ThreadPoolExecutor(max_workers=max(1, parallel)) as pool:
        for case_id, result in pool.map(one, cases):
            results[case_id] = result
            scores = {name: value for name, value in result["scores"].items() if value is not None}
            print(f"  {case_id}: {result['elapsedMs'] / 1000:.1f} s, "
                  + ", ".join(f"{name}={value:.2f}" for name, value in scores.items()))

    pictures = render_results(version_name, results)
    print(f"drew {len(pictures)} maps into {RESULTS_DIR / version_name}")

    print("logging to Galtea ...")
    for case in cases:
        log_case(galtea, config, version_name, version.id, case, results[case["id"]], pictures[case["id"]] if images else None, judge=True)

    summary = summarise(rules, results)
    # The committed file keeps what a reader compares: the map, its scores and the summary.
    # The per-cell probability tables stay in Galtea (in each inference result's output).
    for result in results.values():
        slim_result(result)
    (RESULTS_DIR / f"{version_name}.json").write_text(
        json.dumps({"version": version_name, "versionId": version.id, "createdAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "description": description, "models": {"decision": decision_model, "narrative": narrative_model},
                    "commit": git_description(), "summary": summary, "results": results}, separators=(",", ":")) + "\n",
        encoding="utf8",
    )
    print_summary(rules, summary)
    print(f"done in {time.time() - started:.0f} s -> {RESULTS_DIR / f'{version_name}.json'}")


def log_case(galtea, config: dict, version_name: str, version_id: str, case: dict, result: dict, picture: Path | None, judge: bool) -> None:
    """One session, one inference result, one evaluation per metric, then the session is finished."""
    scores = {name: value for name, value in result["scores"].items() if value is not None}
    session = galtea.sessions.get_or_create(
        custom_id=f"{version_name}:{case['id']}",
        version_id=version_id,
        test_case_id=config["testCaseIds"][case["id"]],
    )
    text = result["ascii"] + "\n\n" + json.dumps(
        {"summary": result["summary"], "scores": result["scores"], "vocabulary": result["vocabulary"]["name"], "grid": result["grid"]}
    )
    # The scored output is the text; the picture rides along as a file part, which the dashboard shows.
    output = {"assistant_message": text, "content": [upload_image(picture)]} if picture else text
    galtea.inference_results.create(session_id=session.id, input=json.dumps(case), output=output, latency=result["elapsedMs"])
    galtea.evaluations.create(
        session_id=session.id,
        metrics=[{"id": config["metricIds"][name], "score": round(value, 4)} for name, value in scores.items()],
    )
    if judge and judge_metric_names(config):
        # No score: Galtea's evaluator reads the output and scores it, asynchronously.
        galtea.evaluations.create(session_id=session.id, metrics=judge_metric_names(config))
    finish_session(session.id)


def slim_result(result: dict) -> None:
    """Drop what the committed file does not need: probabilities, and a shipped vocabulary's text."""
    result["grid"]["cells"] = [
        None if cell is None else {key: value for key, value in cell.items() if key != "probabilities"}
        for cell in result["grid"]["cells"]
    ]
    if result["models"]["vocabulary"].startswith("preset:") and isinstance(result["vocabulary"].get("elements"), list):
        # A shipped vocabulary is in the repository already; keep its name and size only.
        result["vocabulary"] = {"name": result["vocabulary"]["name"], "elements": len(result["vocabulary"]["elements"])}


def score_results(results: dict[str, dict]) -> dict[str, dict]:
    """Today's metrics and ASCII view for saved maps, through rescoreResults.js. Returns case id -> {scores, ascii}."""
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf8") as handle:
        json.dump({"results": results}, handle)
        path = handle.name
    completed = subprocess.run([BUN, str(HERE / "rescoreResults.js"), path], capture_output=True, text=True, encoding="utf8", cwd=PROJECT)
    os.unlink(path)
    if completed.returncode != 0:
        sys.exit(f"rescoreResults.js failed:\n{completed.stderr}")
    return json.loads(completed.stdout)


def summarise(rules: dict, results: dict[str, dict]) -> dict:
    """Mean score per metric and per specification, over the cases that had something to judge."""
    per_metric: dict[str, list[float]] = {metric["name"]: [] for metric in rules["metrics"]}
    for result in results.values():
        for name, value in result["scores"].items():
            if value is not None and name in per_metric:
                per_metric[name].append(value)
    metrics = {name: (statistics.mean(values) if values else None) for name, values in per_metric.items()}
    specifications = {}
    for spec in rules["specifications"]:
        values = [metrics[m["name"]] for m in rules["metrics"] if m["specificationId"] == spec["id"] and metrics[m["name"]] is not None]
        specifications[spec["id"]] = statistics.mean(values) if values else None
    return {"metrics": metrics, "specifications": specifications, "cases": len(results)}


def print_summary(rules: dict, summary: dict, previous: dict | None = None) -> None:
    fmt = lambda value: "  n/a" if value is None else f"{value:5.2f}"
    delta = lambda name, group: (
        "" if previous is None or previous[group].get(name) is None or summary[group].get(name) is None
        else f"  ({summary[group][name] - previous[group][name]:+.2f})"
    )
    for spec in rules["specifications"]:
        print(f"\n{spec['name']}: {fmt(summary['specifications'][spec['id']])}{delta(spec['id'], 'specifications')}")
        for metric in rules["metrics"]:
            if metric["specificationId"] == spec["id"]:
                print(f"    {metric['name']:<28} {fmt(summary['metrics'][metric['name']])}{delta(metric['name'], 'metrics')}")


def render(version_name: str) -> None:
    """Draw the maps of a saved run again, for example after a change to the tileset."""
    path = RESULTS_DIR / f"{version_name}.json"
    if not path.exists():
        sys.exit(f"No local results for {version_name}.")
    saved = json.loads(path.read_text(encoding="utf8"))
    pictures = render_results(version_name, saved["results"])
    print(f"drew {len(pictures)} maps into {RESULTS_DIR / version_name}")


def rescore(version_name: str, push: bool, judge: bool = False) -> None:
    """Score a saved run again with the metrics as they are now, and send the scores that are new to Galtea.

    A metric added after a version ran has no history without this. The grids are in the saved file, so
    no map is generated; `rescoreResults.js` computes the scores and this writes them back and, for the
    metrics the version had not been scored on, creates the evaluations on the version's sessions. With
    `judge`, it also asks Galtea to run every judge metric on every session of the version."""
    galtea = galtea_client() if push else None
    config = read_config()
    rules = read_rules()
    path = RESULTS_DIR / f"{version_name}.json"
    if not path.exists():
        sys.exit(f"No local results for {version_name}.")
    saved = json.loads(path.read_text(encoding="utf8"))
    fresh = score_results(saved["results"])

    sent = 0
    for case_id, result in saved["results"].items():
        before = result["scores"]
        after = fresh[case_id]["scores"]
        new_metrics = {name: value for name, value in after.items() if name not in before and value is not None}
        result["scores"] = after
        if push and (new_metrics or judge) and case_id in config["testCaseIds"]:
            session = galtea.sessions.get_or_create(
                custom_id=f"{version_name}:{case_id}", version_id=saved["versionId"], test_case_id=config["testCaseIds"][case_id]
            )
            if new_metrics:
                galtea.evaluations.create(
                    session_id=session.id,
                    metrics=[{"id": config["metricIds"][name], "score": round(value, 4)} for name, value in new_metrics.items()],
                )
                sent += len(new_metrics)
            if judge and judge_metric_names(config):
                galtea.evaluations.create(session_id=session.id, metrics=judge_metric_names(config))
                sent += len(judge_metric_names(config))
    saved["summary"] = summarise(rules, saved["results"])
    saved["rescoredAt"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    path.write_text(json.dumps(saved, separators=(",", ":")) + "\n", encoding="utf8")
    print_summary(rules, saved["summary"])
    print(f"rescored {len(fresh)} maps" + (f", sent {sent} new scores to Galtea" if push else ""))


def checkout_version(commit: str) -> Path:
    """The project as it was at `commit`, in a temporary folder, with today's backfill runner copied in."""
    target = Path(tempfile.mkdtemp(prefix=f"ai-world-gen-{commit}-"))
    archive = target / "source.zip"
    completed = subprocess.run(
        ["git", "archive", "--format=zip", "-o", str(archive), commit, "web-projects/ai-world-gen"],
        capture_output=True, text=True, cwd=PROJECT.parent.parent,  # the pathspec is relative to the repository root
    )
    if completed.returncode != 0:
        sys.exit(f"git archive {commit} failed:\n{completed.stderr}")
    with zipfile.ZipFile(archive) as bundle:
        bundle.extractall(target)
    archive.unlink()
    project = target / "web-projects" / "ai-world-gen"
    (project / "evaluation").mkdir(exist_ok=True)  # v1 ran before this folder existed
    shutil.copy(HERE / "backfillRun.js", project / "evaluation" / "backfillRun.js")
    return project


def backfill(version_name: str, parallel: int, only: list[str] | None, images: bool = True) -> None:
    """Generate the test cases a version never ran, with that version's own code, and log them into it.

    A dataset added after a version ran leaves that version half evaluated in Galtea. The saved results
    name the commit the version ran from; the project is checked out at that commit into a temporary
    folder and `backfillRun.js` draws each missing map with the modules found there. Today's metrics
    score the map (`rescoreResults.js`), the picture is drawn and uploaded, and the result is merged
    into the saved file. No judge metric is asked for, so old versions stay comparable with each other."""
    galtea = galtea_client()
    config = read_config()
    rules = read_rules()
    path = RESULTS_DIR / f"{version_name}.json"
    if not path.exists():
        sys.exit(f"No local results for {version_name}.")
    saved = json.loads(path.read_text(encoding="utf8"))
    commit = saved["commit"].split()[-1]
    cases = [case for dataset in read_cases()["datasets"] for case in dataset["cases"] if case["id"] not in saved["results"]]
    if only:
        cases = [case for case in cases if case["id"] in only]
    if not cases:
        print(f"{version_name}: nothing to backfill")
        return
    print(f"{version_name}: {len(cases)} cases to generate with the code of commit {commit}")
    project = checkout_version(commit)

    def one(case: dict) -> tuple[str, dict]:
        print(f"  generating {case['id']} ...", flush=True)
        completed = subprocess.run(
            [BUN, str(project / "evaluation" / "backfillRun.js"), json.dumps(case)],
            capture_output=True, text=True, encoding="utf8", cwd=project,
        )
        if completed.returncode != 0:
            raise RuntimeError(f"{case['id']}: {completed.stderr.strip().splitlines()[-1] if completed.stderr else 'failed'}")
        return case["id"], json.loads(completed.stdout)

    fresh: dict[str, dict] = {}
    started = time.time()
    with ThreadPoolExecutor(max_workers=max(1, parallel)) as pool:
        for case_id, result in pool.map(one, cases):
            fresh[case_id] = result
    scored = score_results(fresh)
    for case_id, result in fresh.items():
        result["scores"] = scored[case_id]["scores"]
        result["ascii"] = scored[case_id]["ascii"]
        shown = {name: value for name, value in result["scores"].items() if value is not None}
        print(f"  {case_id}: {result['elapsedMs'] / 1000:.1f} s, " + ", ".join(f"{name}={value:.2f}" for name, value in shown.items()))
    shutil.rmtree(project.parent.parent.parent, ignore_errors=True)

    pictures = render_results(version_name, fresh) if images else {}
    print("logging to Galtea ...")
    for case in cases:
        log_case(galtea, config, version_name, saved["versionId"], case, fresh[case["id"]], pictures.get(case["id"]), judge=False)

    for result in fresh.values():
        slim_result(result)
    saved["results"].update(fresh)
    saved["summary"] = summarise(rules, saved["results"])
    saved["backfilledAt"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    path.write_text(json.dumps(saved, separators=(",", ":")) + "\n", encoding="utf8")
    print_summary(rules, saved["summary"])
    print(f"backfilled {len(fresh)} maps into {version_name} in {time.time() - started:.0f} s")


def report(version_name: str, against: str | None) -> None:
    rules = read_rules()
    path = RESULTS_DIR / f"{version_name}.json"
    if not path.exists():
        sys.exit(f"No local results for {version_name}. Run `python evaluate.py run --version {version_name}` first.")
    current = json.loads(path.read_text(encoding="utf8"))
    previous = None
    if against:
        previous_path = RESULTS_DIR / f"{against}.json"
        if not previous_path.exists():
            sys.exit(f"No local results for {against}.")
        previous = json.loads(previous_path.read_text(encoding="utf8"))["summary"]
    print(f"{version_name}: {current['summary']['cases']} test cases" + (f", compared with {against}" if against else ""))
    print_summary(rules, current["summary"], previous)


