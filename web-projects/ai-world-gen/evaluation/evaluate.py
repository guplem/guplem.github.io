"""Evaluate AI World Gen against its specifications, in Galtea.

Three commands, run from this folder or from anywhere:

    python evaluate.py setup                  # create or find the Galtea product, specifications, metrics, datasets
    python evaluate.py run --version v2       # generate every test case, log it as a session, score it
    python evaluate.py report --version v2    # print the scores of a version, and the change since another

`setup` is idempotent: it matches everything by name and writes the ids to
`galtea.json`, which is committed. `run` needs two keys in the environment:
OPENROUTER_API_KEY for the generation and GALTEA_API_KEY for Galtea (the
key the `galtea` CLI stored with `galtea login` is used when the variable is
not set).

The map itself is generated by `runTestCase.js` with the same modules the
page uses, and scored by `mapMetrics.js`. This file only talks to Galtea:
one session per test case and version, one inference result (the input
parameters and the finished map), one evaluation per metric with the score
computed locally (a self-hosted metric in Galtea's terms). ADR 0005 says why.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
CONFIG_PATH = HERE / "galtea.json"
CASES_PATH = HERE / "testCases.json"
RESULTS_DIR = HERE / "results"
ENV_PATH = HERE / ".env"


def load_dotenv() -> None:
    """Read KEY=value lines from `evaluation/.env` (git-ignored) into the environment, without overriding it."""
    if not ENV_PATH.exists():
        return
    for line in ENV_PATH.read_text(encoding="utf8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.split(" #", 1)[0].strip().strip('"').strip("'")
        if value:
            os.environ.setdefault(key.strip(), value)


load_dotenv()

PRODUCT_NAME = "AI World Gen"
PRODUCT_DESCRIPTION = (
    "A map generator with two kinds of AI: a language model writes a world's vocabulary once, "
    "and a decision model (TypeSafe's Jev through OpenRouter) places every cell from its neighbours. "
    "https://triunitystudios.com/web-projects/ai-world-gen/"
)


# --------------------------------------------------------------------------- #
# Keys and clients
# --------------------------------------------------------------------------- #


def galtea_api_key() -> str:
    """GALTEA_API_KEY, or the key the CLI stored with `galtea login`."""
    key = os.environ.get("GALTEA_API_KEY", "").strip()
    if key:
        return key
    config_dir = os.environ.get("GALTEA_CONFIG_DIR") or (
        Path(os.environ["APPDATA"]) / "galtea" if os.name == "nt" else Path.home() / ".config" / "galtea"
    )
    apis = Path(config_dir) / "apis.json"
    if apis.exists():
        raw = json.loads(apis.read_text(encoding="utf8")).get("raw", {})
        header = raw.get("profiles", {}).get("default", {}).get("headers", {}).get("authorization", "")
        if header.startswith("Bearer gsk_"):
            return header[len("Bearer ") :]
    sys.exit("No Galtea key: set GALTEA_API_KEY or run `galtea login`.")


def galtea_client():
    from galtea import Galtea

    return Galtea(api_key=galtea_api_key())


def executable(name: str) -> str:
    """The full path of a command. Windows needs the `.exe`, and Bun installs outside the system PATH."""
    found = shutil.which(name) or shutil.which(f"{name}.exe")
    if found:
        return found
    for candidate in (Path.home() / ".bun" / "bin" / f"{name}.exe", Path.home() / ".bun" / "bin" / name):
        if candidate.exists():
            return str(candidate)
    sys.exit(f"`{name}` was not found on PATH.")


BUN = executable("bun")
GALTEA_CLI = executable("galtea")


def cli(*args: str, stdin: dict | None = None) -> dict | list:
    """Run one `galtea` CLI command and parse its JSON. The CLI covers the two calls the SDK lacks."""
    env = {**os.environ, "GALTEA_API_KEY": galtea_api_key(), "NO_COLOR": "1"}
    completed = subprocess.run(
        [GALTEA_CLI, *args],
        input=json.dumps(stdin) if stdin is not None else None,
        capture_output=True,
        text=True,
        encoding="utf8",
        env=env,
    )
    if completed.returncode != 0:
        sys.exit(f"galtea {' '.join(args)} failed:\n{completed.stderr or completed.stdout}")
    return json.loads(completed.stdout)


# --------------------------------------------------------------------------- #
# The rules, read from the JavaScript that computes them
# --------------------------------------------------------------------------- #


def read_rules() -> dict:
    """SPECIFICATIONS and METRICS from mapMetrics.js, so the names exist in one place."""
    script = (
        "import { METRICS, SPECIFICATIONS } from './mapMetrics.js';"
        "console.log(JSON.stringify({ specifications: SPECIFICATIONS, metrics: METRICS }));"
    )
    completed = subprocess.run([BUN, "-e", script], capture_output=True, text=True, encoding="utf8", cwd=HERE)
    if completed.returncode != 0:
        sys.exit(f"Could not read mapMetrics.js:\n{completed.stderr}")
    return json.loads(completed.stdout)


def read_cases() -> dict:
    return json.loads(CASES_PATH.read_text(encoding="utf8"))


def read_config() -> dict:
    return json.loads(CONFIG_PATH.read_text(encoding="utf8")) if CONFIG_PATH.exists() else {}


def write_config(config: dict) -> None:
    CONFIG_PATH.write_text(json.dumps(config, indent=2) + "\n", encoding="utf8")


# --------------------------------------------------------------------------- #
# setup
# --------------------------------------------------------------------------- #


def setup() -> None:
    galtea = galtea_client()
    rules = read_rules()
    cases = read_cases()
    config = read_config()

    # Product: GALTEA_PRODUCT_ID adopts an existing one; otherwise match by name; otherwise
    # create it (the SDK cannot create a product, the CLI can).
    all_products = cli("products", "list")
    wanted_id = os.environ.get("GALTEA_PRODUCT_ID", "").strip() or config.get("productId", "")
    products = [one for one in all_products if one["id"] == wanted_id] or [one for one in all_products if one["name"] == PRODUCT_NAME]
    if products:
        product = products[0]
        print(f"product: found {product['id']} ({product['name']})")
    else:
        # The organization: GALTEA_ORGANIZATION_ID, or the one that holds most of the key's products.
        organization_id = os.environ.get("GALTEA_ORGANIZATION_ID", "").strip()
        if not organization_id:
            counts: dict[str, int] = {}
            for one in all_products:
                counts[one["organizationId"]] = counts.get(one["organizationId"], 0) + 1
            organization_id = max(counts, key=counts.get) if counts else cli("organizations", "list")[0]["id"]
        product = cli(
            "products",
            "create",
            stdin={
                "name": PRODUCT_NAME,
                "description": PRODUCT_DESCRIPTION,
                "organizationId": organization_id,
                "interactionMode": "HUMAN_DIRECT",
                "capabilities": "Generates a coherent tile map for any described setting, one typed decision per cell.",
                "inabilities": "Does not write stories, does not simulate a player, does not run without an OpenRouter key.",
            },
        )
        print(f"product: created {product['id']}")
    config["productId"] = product["id"]

    # Metrics: self-hosted, one per rule in mapMetrics.js, matched by name.
    existing = {one.name: one for one in galtea.metrics.list(limit=500)}
    config["metricIds"] = {}
    for metric in rules["metrics"]:
        found = existing.get(metric["name"])
        if found is None:
            found = galtea.metrics.create(
                name=metric["name"],
                source="self_hosted",
                description=metric["description"],
                tags=["ai-world-gen", metric["specificationId"]],
            )
            if found is None:
                sys.exit(f"Could not create metric {metric['name']}")
            print(f"metric: created {metric['name']}")
        config["metricIds"][metric["name"]] = found.id

    # Specifications: matched by name through the CLI (the SDK create has no name).
    all_specs = cli("specifications", "list", "--product-ids", product["id"])
    config["specificationIds"] = {}
    for spec in rules["specifications"]:
        metric_ids = [config["metricIds"][m["name"]] for m in rules["metrics"] if m["specificationId"] == spec["id"]]
        found = next((one for one in all_specs if one["name"] == spec["name"]), None)
        if found is None:
            found = cli(
                "specifications",
                "create",
                stdin={
                    "name": spec["name"],
                    "description": spec["description"],
                    "productId": product["id"],
                    "type": "POLICY",
                    "testType": "QUALITY",
                    "testVariant": "other",
                    "metricIds": metric_ids,
                    "useForTestAlignment": True,
                },
            )
            print(f"specification: created {spec['name']}")
        else:
            # Linking an already linked metric is a 409, so link only the new ones.
            missing = [one for one in metric_ids if one not in (found.get("metricIds") or [])]
            if missing:
                galtea.specifications.link_metrics(found["id"], missing)
        config["specificationIds"][spec["id"]] = found["id"]

    # Datasets: one per specification, uploaded as CSV, then linked. Test cases matched by their id in the input.
    tests = {one.name: one for one in galtea.tests.list(product_id=product["id"], limit=500)}
    config["testIds"] = {}
    config["testCaseIds"] = {}
    for dataset in cases["datasets"]:
        test = tests.get(dataset["name"])
        if test is None:
            with tempfile.NamedTemporaryFile("w", suffix=".csv", delete=False, newline="", encoding="utf8") as handle:
                writer = csv.writer(handle)
                writer.writerow(["instance_id", "input", "expected_output", "tag", "source"])
                for index, case in enumerate(dataset["cases"]):
                    writer.writerow([index, json.dumps(case), "", "original", "manual"])
                csv_path = handle.name
            test = galtea.tests.create(
                name=dataset["name"],
                type="QUALITY",
                product_id=product["id"],
                test_file_path=csv_path,
                metadata={"specification": dataset["specificationId"], "source": "evaluation/testCases.json"},
            )
            os.unlink(csv_path)
            print(f"dataset: created {dataset['name']}")
        specification_id = config["specificationIds"][dataset["specificationId"]]
        linked = {one.id for one in galtea.specifications.get_tests(specification_id)}
        if test.id not in linked:
            galtea.specifications.link_tests(specification_id, [test.id])
        config["testIds"][dataset["specificationId"]] = test.id

        # Match the uploaded rows back to our case ids.
        for _ in range(30):
            uploaded = galtea.test_cases.list(test_id=test.id, limit=100)
            if len(uploaded) >= len(dataset["cases"]):
                break
            time.sleep(2)
        for row in uploaded:
            # Galtea parsed the JSON in the CSV into an object: `input_data` holds it, `input` is None.
            data = getattr(row, "input_data", None)
            if not isinstance(data, dict) and isinstance(row.input, str):
                try:
                    data = json.loads(row.input)
                except json.JSONDecodeError:
                    data = None
            case_id = data.get("id") if isinstance(data, dict) else None
            if case_id:
                config["testCaseIds"][case_id] = row.id
        missing = [case["id"] for case in dataset["cases"] if case["id"] not in config["testCaseIds"]]
        if missing:
            sys.exit(f"Test cases not found in Galtea after upload: {missing}")

    write_config(config)
    print(f"setup done: {len(config['metricIds'])} metrics, {len(config['specificationIds'])} specifications, "
          f"{len(config['testCaseIds'])} test cases -> {CONFIG_PATH.name}")


# --------------------------------------------------------------------------- #
# run
# --------------------------------------------------------------------------- #


def generate(case: dict) -> dict:
    """One map for one test case, through the Bun runner."""
    if not os.environ.get("OPENROUTER_API_KEY"):
        sys.exit("Set OPENROUTER_API_KEY to generate maps.")
    completed = subprocess.run(
        [BUN, str(HERE / "runTestCase.js"), json.dumps(case)],
        capture_output=True,
        text=True,
        encoding="utf8",
        cwd=PROJECT,
    )
    if completed.returncode != 0:
        raise RuntimeError(f"{case['id']}: {completed.stderr.strip().splitlines()[-1] if completed.stderr else 'failed'}")
    return json.loads(completed.stdout)


def git_description() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=PROJECT).stdout.strip()
        return f"commit {sha}"
    except OSError:
        return "unknown commit"


def run(version_name: str, description: str | None, parallel: int, only: list[str] | None) -> None:
    galtea = galtea_client()
    config = read_config()
    if not config.get("testCaseIds"):
        sys.exit("Run `python evaluate.py setup` first.")
    rules = read_rules()
    cases = [case for dataset in read_cases()["datasets"] for case in dataset["cases"]]
    if only:
        cases = [case for case in cases if case["id"] in only]

    decision_model = os.environ.get("AI_WORLD_GEN_DECISION_MODEL") or "~typesafe/jev-latest"
    narrative_model = os.environ.get("AI_WORLD_GEN_NARRATIVE_MODEL") or "anthropic/claude-sonnet-5"
    models_line = f"decision model {decision_model}; narrative model {narrative_model}"
    try:
        version = galtea.versions.get_by_name(config["productId"], version_name)
    except Exception:  # the SDK raises EntityNotFoundException for a name that does not exist yet
        version = None
    if version is None:
        version = galtea.versions.create(
            product_id=config["productId"],
            name=version_name,
            description=f"{description or 'AI World Gen'} ({git_description()}; {models_line})",
            model_id=None,
        )
        if version is None:
            sys.exit("Could not create the version.")
        print(f"version: created {version_name} ({version.id})")
    else:
        print(f"version: found {version_name} ({version.id})")

    RESULTS_DIR.mkdir(exist_ok=True)
    results: dict[str, dict] = {}
    started = time.time()

    def one(case: dict) -> tuple[str, dict]:
        print(f"  generating {case['id']} ...", flush=True)
        return case["id"], generate(case)

    with ThreadPoolExecutor(max_workers=max(1, parallel)) as pool:
        for case_id, result in pool.map(one, cases):
            results[case_id] = result
            scores = {name: value for name, value in result["scores"].items() if value is not None}
            print(f"  {case_id}: {result['elapsedMs'] / 1000:.1f} s, "
                  + ", ".join(f"{name}={value:.2f}" for name, value in scores.items()))

    print("logging to Galtea ...")
    for case in cases:
        result = results[case["id"]]
        scores = {name: value for name, value in result["scores"].items() if value is not None}
        session = galtea.sessions.get_or_create(
            custom_id=f"{version_name}:{case['id']}",
            version_id=version.id,
            test_case_id=config["testCaseIds"][case["id"]],
        )
        output = result["ascii"] + "\n\n" + json.dumps(
            {"summary": result["summary"], "scores": result["scores"], "vocabulary": result["vocabulary"]["name"], "grid": result["grid"]}
        )
        galtea.inference_results.create(
            session_id=session.id,
            input=json.dumps(case),
            output=output,
            latency=result["elapsedMs"],
        )
        galtea.evaluations.create(
            session_id=session.id,
            metrics=[{"id": config["metricIds"][name], "score": round(value, 4)} for name, value in scores.items()],
        )

    summary = summarise(rules, results)
    # The committed file keeps what a reader compares: the map, its scores and the summary.
    # The per-cell probability tables stay in Galtea (in each inference result's output).
    for result in results.values():
        result["grid"]["cells"] = [
            None if cell is None else {key: value for key, value in cell.items() if key != "probabilities"}
            for cell in result["grid"]["cells"]
        ]
        if result["models"]["vocabulary"].startswith("preset:"):
            # A shipped vocabulary is in the repository already; keep its name and size only.
            result["vocabulary"] = {"name": result["vocabulary"]["name"], "elements": len(result["vocabulary"]["elements"])}
    (RESULTS_DIR / f"{version_name}.json").write_text(
        json.dumps({"version": version_name, "versionId": version.id, "createdAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "description": description, "models": {"decision": decision_model, "narrative": narrative_model},
                    "commit": git_description(), "summary": summary, "results": results}, separators=(",", ":")) + "\n",
        encoding="utf8",
    )
    print_summary(rules, summary)
    print(f"done in {time.time() - started:.0f} s -> {RESULTS_DIR / f'{version_name}.json'}")


def summarise(rules: dict, results: dict[str, dict]) -> dict:
    """Mean score per metric and per specification, over the cases that had something to judge."""
    per_metric: dict[str, list[float]] = {metric["name"]: [] for metric in rules["metrics"]}
    for result in results.values():
        for name, value in result["scores"].items():
            if value is not None and name in per_metric:
                per_metric[name].append(value)
    metrics = {name: (statistics.mean(values) if values else None) for name, values in per_metric.items()}
    specifications = {}
    for spec in rules["specifications"]:
        values = [metrics[m["name"]] for m in rules["metrics"] if m["specificationId"] == spec["id"] and metrics[m["name"]] is not None]
        specifications[spec["id"]] = statistics.mean(values) if values else None
    return {"metrics": metrics, "specifications": specifications, "cases": len(results)}


def print_summary(rules: dict, summary: dict, previous: dict | None = None) -> None:
    fmt = lambda value: "  n/a" if value is None else f"{value:5.2f}"
    delta = lambda name, group: (
        "" if previous is None or previous[group].get(name) is None or summary[group].get(name) is None
        else f"  ({summary[group][name] - previous[group][name]:+.2f})"
    )
    for spec in rules["specifications"]:
        print(f"\n{spec['name']}: {fmt(summary['specifications'][spec['id']])}{delta(spec['id'], 'specifications')}")
        for metric in rules["metrics"]:
            if metric["specificationId"] == spec["id"]:
                print(f"    {metric['name']:<28} {fmt(summary['metrics'][metric['name']])}{delta(metric['name'], 'metrics')}")


def report(version_name: str, against: str | None) -> None:
    rules = read_rules()
    path = RESULTS_DIR / f"{version_name}.json"
    if not path.exists():
        sys.exit(f"No local results for {version_name}. Run `python evaluate.py run --version {version_name}` first.")
    current = json.loads(path.read_text(encoding="utf8"))
    previous = None
    if against:
        previous_path = RESULTS_DIR / f"{against}.json"
        if not previous_path.exists():
            sys.exit(f"No local results for {against}.")
        previous = json.loads(previous_path.read_text(encoding="utf8"))["summary"]
    print(f"{version_name}: {current['summary']['cases']} test cases" + (f", compared with {against}" if against else ""))
    print_summary(rules, current["summary"], previous)


# --------------------------------------------------------------------------- #


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("setup", help="create or find the Galtea product, metrics, specifications and datasets")
    run_parser = commands.add_parser("run", help="generate and score every test case for one version")
    run_parser.add_argument("--version", required=True, help="the version name in Galtea, e.g. v1")
    run_parser.add_argument("--description", help="what changed in this version")
    run_parser.add_argument("--parallel", type=int, default=3, help="maps generated at the same time (default 3)")
    run_parser.add_argument("--only", nargs="*", help="run only these test case ids")
    report_parser = commands.add_parser("report", help="print the scores of a version from the local results")
    report_parser.add_argument("--version", required=True)
    report_parser.add_argument("--against", help="another version to show the change against")
    args = parser.parse_args()

    if args.command == "setup":
        setup()
    elif args.command == "run":
        run(args.version, args.description, args.parallel, args.only)
    else:
        report(args.version, args.against)


if __name__ == "__main__":
    main()
