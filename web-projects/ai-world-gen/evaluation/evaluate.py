RESULTS_DIR = HERE / "results"
ENV_PATH = HERE / ".env"


def load_dotenv() -> None:
    """Read KEY=value lines from `evaluation/.env` (git-ignored) into the environment, without overriding it."""
    if not ENV_PATH.exists():
        return
    for line in ENV_PATH.read_text(encoding="utf8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.split(" #", 1)[0].strip().strip('"').strip("'")
        if value:
            os.environ.setdefault(key.strip(), value)


load_dotenv()

PRODUCT_NAME = "AI World Gen"
# The model Galtea uses to score the judge metrics. One of `galtea evaluator-models list`, pinned like the others.
JUDGE_MODEL = os.environ.get("AI_WORLD_GEN_JUDGE_MODEL") or "GPT-5.2"
PRODUCT_DESCRIPTION = (
    "A map generator with two kinds of AI: a language model writes a world's vocabulary once, "
    "and a decision model (TypeSafe's Jev through OpenRouter) places every cell from its neighbours. "
    "https://triunitystudios.com/web-projects/ai-world-gen/"
)


