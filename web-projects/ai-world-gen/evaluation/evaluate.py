def setup() -> None:
    galtea = galtea_client()
    rules = read_rules()
    cases = read_cases()
    config = read_config()

    # Product: GALTEA_PRODUCT_ID adopts an existing one; otherwise match by name; otherwise
    # create it (the SDK cannot create a product, the CLI can).
    all_products = cli("products", "list")
    wanted_id = os.environ.get("GALTEA_PRODUCT_ID", "").strip() or config.get("productId", "")
    products = [one for one in all_products if one["id"] == wanted_id] or [one for one in all_products if one["name"] == PRODUCT_NAME]
    if products:
        product = products[0]
        print(f"product: found {product['id']} ({product['name']})")
    else:
        # The organization: GALTEA_ORGANIZATION_ID, or the one that holds most of the key's products.
        organization_id = os.environ.get("GALTEA_ORGANIZATION_ID", "").strip()
        if not organization_id:
            counts: dict[str, int] = {}
            for one in all_products:
                counts[one["organizationId"]] = counts.get(one["organizationId"], 0) + 1
            organization_id = max(counts, key=counts.get) if counts else cli("organizations", "list")[0]["id"]
        product = cli(
            "products",
            "create",
            stdin={
                "name": PRODUCT_NAME,
                "description": PRODUCT_DESCRIPTION,
                "organizationId": organization_id,
                "interactionMode": "HUMAN_DIRECT",
                "capabilities": "Generates a coherent tile map for any described setting, one typed decision per cell.",
                "inabilities": "Does not write stories, does not simulate a player, does not run without an OpenRouter key.",
            },
        )
        print(f"product: created {product['id']}")
    config["productId"] = product["id"]

    # Metrics: self-hosted, one per rule in mapMetrics.js, matched by name.
    existing = {one.name: one for one in galtea.metrics.list(limit=500)}
    config["metricIds"] = {}
    for metric in rules["metrics"]:
        found = existing.get(metric["name"])
        if found is None:
            found = galtea.metrics.create(
                name=metric["name"],
                source="self_hosted",
                description=metric["description"],
                tags=["ai-world-gen", metric["specificationId"]],
            )
            if found is None:
                sys.exit(f"Could not create metric {metric['name']}")
            print(f"metric: created {metric['name']}")
        config["metricIds"][metric["name"]] = found.id

    # Judge metrics: Galtea's own evaluator reads the output against the prompt in mapMetrics.js.
    config["judgeMetricIds"] = {}
    for metric in rules["judgeMetrics"]:
        found = existing.get(metric["name"])
        if found is None:
            found = galtea.metrics.create(
                name=metric["name"],
                source="partial_prompt",
                evaluator_model_name=JUDGE_MODEL,
                judge_prompt=metric["judgePrompt"],
                evaluation_params=["input", "actual_output"],
                description=metric["description"],
                tags=["ai-world-gen", metric["specificationId"], "judge"],
            )
            if found is None:
                sys.exit(f"Could not create judge metric {metric['name']}")
            print(f"judge metric: created {metric['name']}")
        config["judgeMetricIds"][metric["name"]] = found.id

    # Specifications: matched by name through the CLI (the SDK create has no name).
    all_specs = cli("specifications", "list", "--product-ids", product["id"])
    config["specificationIds"] = {}
    for spec in rules["specifications"]:
        metric_ids = [config["metricIds"][m["name"]] for m in rules["metrics"] if m["specificationId"] == spec["id"]]
        metric_ids += [config["judgeMetricIds"][m["name"]] for m in rules["judgeMetrics"] if m["specificationId"] == spec["id"]]
        found = next((one for one in all_specs if one["name"] == spec["name"]), None)
        if found is None:
            found = cli(
                "specifications",
                "create",
                stdin={
                    "name": spec["name"],
                    "description": spec["description"],
                    "productId": product["id"],
                    "type": "POLICY",
                    "testType": "QUALITY",
                    "testVariant": "other",
                    "metricIds": metric_ids,
                    "useForTestAlignment": True,
                },
            )
            print(f"specification: created {spec['name']}")
        else:
            # Linking an already linked metric is a 409, so link only the new ones.
            missing = [one for one in metric_ids if one not in (found.get("metricIds") or [])]
            if missing:
                galtea.specifications.link_metrics(found["id"], missing)
        config["specificationIds"][spec["id"]] = found["id"]

    # Datasets: one or more per specification, uploaded as CSV, then linked. Test cases matched by their id in the input.
    tests = {one.name: one for one in galtea.tests.list(product_id=product["id"], limit=500)}
    config["testIds"] = {}
    config["testCaseIds"] = {}
    for dataset in cases["datasets"]:
        test = tests.get(dataset["name"])
        if test is None:
            with tempfile.NamedTemporaryFile("w", suffix=".csv", delete=False, newline="", encoding="utf8") as handle:
                writer = csv.writer(handle)
                writer.writerow(["instance_id", "input", "expected_output", "tag", "source"])
                for index, case in enumerate(dataset["cases"]):
                    writer.writerow([index, json.dumps(case), "", "original", "manual"])
                csv_path = handle.name
            test = galtea.tests.create(
                name=dataset["name"],
                type="QUALITY",
                product_id=product["id"],
                test_file_path=csv_path,
                metadata={"specification": dataset["specificationId"], "source": "evaluation/testCases.json"},
            )
            os.unlink(csv_path)
            print(f"dataset: created {dataset['name']}")
        specification_id = config["specificationIds"][dataset["specificationId"]]
        linked = {one.id for one in galtea.specifications.get_tests(specification_id)}
        if test.id not in linked:
            galtea.specifications.link_tests(specification_id, [test.id])
        config["testIds"][dataset["name"]] = test.id

        # Match the uploaded rows back to our case ids.
        for _ in range(30):
            uploaded = galtea.test_cases.list(test_id=test.id, limit=100)
            if len(uploaded) >= len(dataset["cases"]):
                break
            time.sleep(2)
        for row in uploaded:
            # Galtea parsed the JSON in the CSV into an object: `input_data` holds it, `input` is None.
            data = getattr(row, "input_data", None)
            if not isinstance(data, dict) and isinstance(row.input, str):
                try:
                    data = json.loads(row.input)
                except json.JSONDecodeError:
                    data = None
            case_id = data.get("id") if isinstance(data, dict) else None
            if case_id:
                config["testCaseIds"][case_id] = row.id
        missing = [case["id"] for case in dataset["cases"] if case["id"] not in config["testCaseIds"]]
        if missing:
            sys.exit(f"Test cases not found in Galtea after upload: {missing}")

    write_config(config)
    print(f"setup done: {len(config['metricIds'])} metrics, {len(config['specificationIds'])} specifications, "
          f"{len(config['testCaseIds'])} test cases -> {CONFIG_PATH.name}")


