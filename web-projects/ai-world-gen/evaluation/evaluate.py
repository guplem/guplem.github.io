def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("setup", help="create or find the Galtea product, metrics, specifications and datasets")
    run_parser = commands.add_parser("run", help="generate and score every test case for one version")
    run_parser.add_argument("--version", required=True, help="the version name in Galtea, e.g. v1")
    run_parser.add_argument("--description", help="what changed in this version")
    run_parser.add_argument("--parallel", type=int, default=3, help="maps generated at the same time (default 3)")
    run_parser.add_argument("--only", nargs="*", help="run only these test case ids")
    run_parser.add_argument("--no-images", action="store_true", help="draw the maps locally but do not upload them to Galtea")
    report_parser = commands.add_parser("report", help="print the scores of a version from the local results")
    report_parser.add_argument("--version", required=True)
    report_parser.add_argument("--against", help="another version to show the change against")
    render_parser = commands.add_parser("render", help="draw results/<version>/<case>.png again from the saved results")
    render_parser.add_argument("--version", required=True)
    rescore_parser = commands.add_parser("rescore", help="score the saved maps of a version again with the current metrics")
    rescore_parser.add_argument("--version", required=True)
    rescore_parser.add_argument("--no-push", action="store_true", help="write the scores locally, send nothing to Galtea")
    rescore_parser.add_argument("--judge", action="store_true", help="also ask Galtea to run the judge metrics on every session of the version")
    backfill_parser = commands.add_parser("backfill", help="generate the test cases a version never ran, with that version's code")
    backfill_parser.add_argument("--version", required=True)
    backfill_parser.add_argument("--parallel", type=int, default=3)
    backfill_parser.add_argument("--only", nargs="*", help="run only these test case ids")
    backfill_parser.add_argument("--no-images", action="store_true")
    args = parser.parse_args()

    if args.command == "setup":
        setup()
    elif args.command == "run":
        run(args.version, args.description, args.parallel, args.only, images=not args.no_images)
    elif args.command == "render":
        render(args.version)
    elif args.command == "rescore":
        rescore(args.version, push=not args.no_push, judge=args.judge)
    elif args.command == "backfill":
        backfill(args.version, args.parallel, args.only, images=not args.no_images)
    else:
        report(args.version, args.against)


if __name__ == "__main__":
    main()
