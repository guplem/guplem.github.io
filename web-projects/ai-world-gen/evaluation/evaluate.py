"""Evaluate AI World Gen against its specifications, in Galtea.

Five commands, run from this folder or from anywhere:

    python evaluate.py setup                  # create or find the Galtea product, specifications, metrics, datasets
    python evaluate.py run --version v2       # generate every test case, log it as a session, score it
    python evaluate.py report --version v2    # print the scores of a version, and the change since another
    python evaluate.py render --version v2    # draw results/v2/<case>.png again from the saved results
    python evaluate.py rescore --version v2   # score the saved maps again with the metrics as they are now, and send the new scores
    python evaluate.py backfill --version v2  # generate the test cases v2 never ran, with v2's own code, and log them into v2

Every map is also drawn as a PNG (`renderMap.py`), saved under `results/vN/`,
uploaded to Galtea's storage and attached to the inference result's output as
a file part next to the ASCII map, so the dashboard shows the picture. Pass
`--no-images` to skip the upload.

`setup` is idempotent: it matches everything by name and writes the ids to
`galtea.json`, which is committed. `run` needs two keys in the environment:
OPENROUTER_API_KEY for the generation and GALTEA_API_KEY for Galtea (the
key the `galtea` CLI stored with `galtea login` is used when the variable is
not set).

The map itself is generated by `runTestCase.js` with the same modules the
page uses, and scored by `mapMetrics.js`. This file only talks to Galtea:
one session per test case and version, one inference result (the input
parameters and the finished map), one evaluation per metric with the score
computed locally (a self-hosted metric in Galtea's terms), one evaluation
per judge metric that Galtea scores itself, and the session is finished at
once, because a map is one turn. ADR 0005 says why.
"""

