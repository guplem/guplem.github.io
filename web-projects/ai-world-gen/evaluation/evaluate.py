def galtea_api_key() -> str:
    """GALTEA_API_KEY, or the key the CLI stored with `galtea login`."""
    key = os.environ.get("GALTEA_API_KEY", "").strip()
    if key:
        return key
    config_dir = os.environ.get("GALTEA_CONFIG_DIR") or (
        Path(os.environ["APPDATA"]) / "galtea" if os.name == "nt" else Path.home() / ".config" / "galtea"
    )
    apis = Path(config_dir) / "apis.json"
    if apis.exists():
        raw = json.loads(apis.read_text(encoding="utf8")).get("raw", {})
        header = raw.get("profiles", {}).get("default", {}).get("headers", {}).get("authorization", "")
        if header.startswith("Bearer gsk_"):
            return header[len("Bearer ") :]
    sys.exit("No Galtea key: set GALTEA_API_KEY or run `galtea login`.")


def galtea_client():
    from galtea import Galtea

    return Galtea(api_key=galtea_api_key())


def executable(name: str) -> str:
    """The full path of a command. Windows needs the `.exe`, and Bun installs outside the system PATH."""
    found = shutil.which(name) or shutil.which(f"{name}.exe")
    if found:
        return found
    for candidate in (Path.home() / ".bun" / "bin" / f"{name}.exe", Path.home() / ".bun" / "bin" / name):
        if candidate.exists():
            return str(candidate)
    sys.exit(f"`{name}` was not found on PATH.")


BUN = executable("bun")
GALTEA_CLI = executable("galtea")


def cli(*args: str, stdin: dict | None = None) -> dict | list:
    """Run one `galtea` CLI command and parse its JSON. The CLI covers the two calls the SDK lacks."""
    env = {**os.environ, "GALTEA_API_KEY": galtea_api_key(), "NO_COLOR": "1"}
    completed = subprocess.run(
        [GALTEA_CLI, *args],
        input=json.dumps(stdin) if stdin is not None else None,
        capture_output=True,
        text=True,
        encoding="utf8",
        env=env,
    )
    if completed.returncode != 0:
        sys.exit(f"galtea {' '.join(args)} failed:\n{completed.stderr or completed.stdout}")
    return json.loads(completed.stdout)


